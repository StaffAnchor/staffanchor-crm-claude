import { createClient } from "@/lib/supabase/server";
import { redirect } from "next/navigation";
import PlacementsView, { type PlacementRow, type RetentionCheckin } from "./placements-view";
import { adminDb } from "@/lib/pro-sessions/core";
import { loadDropped } from "@/lib/placements/drops";
import DroppedSection from "@/components/placements/dropped-section";
import FeeAnalysisView from "@/components/placements/fee-analysis-view";
import { feeStageFromRow, loadFeeAnalysis } from "@/lib/placements/fee-analysis";
import Link from "next/link";

// Source-of-truth placement tracker: every candidate at stage="placed",
// their joining date, and the recruiter's confirmation of what actually
// happened on/around that date (joined on time / joined but postponed /
// did not join). Billing (Offered CTC x client fee % + 18% GST) is
// computed here from the same offered_fixed_ctc + clients.fee_percentage
// that fn_create_fee_tranches() (see migration) uses to generate the
// actual fee-tranche rows on the Billing page -- this table is a faster,
// flatter read of "who's placed and what are we owed", not a replacement
// for the tranche-level invoicing workflow.
//
// Visible to every recruiter (not admin-gated like the rest of Analytics)
// since DOJ + join confirmation is something any recruiter working a
// placement needs to update. Only the Offered CTC / billing figures are
// admin-editable (enforced via the admin_set_offered_ctc() RPC, not just
// hidden in the UI, since RLS otherwise grants any staff full row access).
//
// Also folds in the 30/90/180-day post-placement retention check-ins
// (formerly a separate /retention page) -- these are auto-generated by
// fn_create_retention_checkins() the moment a link is stage=placed with a
// join date and hasn't been marked did_not_join (see the retention-checkin
// lifecycle migration), so keeping them here next to the DOJ/confirmation
// that drives them means one place to look instead of two, and no more
// stale check-ins sitting around for candidates who turned out not to
// have actually joined.
export default async function PlacementsPage({ searchParams }: { searchParams: Promise<{ view?: string }> }) {
  const sp = await searchParams;
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) redirect("/login");

  const { data: myProfile } = await supabase.from("profiles").select("role").eq("id", user.id).single();
  const isAdmin = myProfile?.role === "admin";
  const analysis = isAdmin && sp.view === "analysis";
  const admin = adminDb();

  const { data, error } = await supabase
    .from("candidate_mandate_links")
    .select(
      "id, candidate_id, mandate_id, date_of_joining, offered_fixed_ctc, join_status, join_status_updated_at, stage_updated_at, candidates(full_name, owner_id, expected_fixed_ctc, current_fixed_ctc), mandates(role_title, client_name, client_id, clients(fee_percentage)), placement_retention_checkins(id, checkin_type, due_date, completed_at, outcome, notes)"
    )
    .eq("stage", "placed")
    .order("date_of_joining", { ascending: false, nullsFirst: false });

  const rows: PlacementRow[] = (error ? [] : data ?? []).map((r) => {
    const candidate = r.candidates as unknown as {
      full_name: string;
      owner_id: string | null;
      expected_fixed_ctc: number | null;
      current_fixed_ctc: number | null;
    } | null;
    const mandate = r.mandates as unknown as {
      role_title: string;
      client_name: string;
      client_id: string | null;
      clients: { fee_percentage: number } | null;
    } | null;
    const fallbackCtc = candidate?.expected_fixed_ctc ?? candidate?.current_fixed_ctc ?? null;
    const checkins = (r.placement_retention_checkins ?? []) as unknown as RetentionCheckin[];
    return {
      linkId: r.id,
      candidateId: r.candidate_id,
      mandateId: r.mandate_id,
      candidateName: candidate?.full_name ?? "Unknown",
      ownerId: candidate?.owner_id ?? null,
      roleTitle: mandate?.role_title ?? "—",
      clientName: mandate?.client_name ?? "—",
      hasClientLink: !!mandate?.client_id,
      feePercentage: mandate?.clients?.fee_percentage ?? null,
      dateOfJoining: r.date_of_joining,
      offeredFixedCtc: r.offered_fixed_ctc,
      fallbackCtc,
      joinStatus: r.join_status,
      joinStatusUpdatedAt: r.join_status_updated_at,
      stageUpdatedAt: r.stage_updated_at,
      checkins: [...checkins].sort((a, b) => a.due_date.localeCompare(b.due_date)),
    };
  });

  // Admins also see each placement's fees and the stage they are in, so a fee can be moved from the tracker.
  if (isAdmin && admin && rows.length) {
    const { data: fees } = await admin
      .from("placement_fee_tranches")
      .select("id, link_id, label, amount_lakhs, status, proforma_sent_at, final_invoiced_at, payment_received_at, cancelled_at")
      .in("link_id", rows.map((r) => r.linkId));
    const by = new Map<string, NonNullable<PlacementRow["fees"]>>();
    for (const f of (fees ?? []) as { id: string; link_id: string; label: string | null; amount_lakhs: number | string | null; status: string; proforma_sent_at: string | null; final_invoiced_at: string | null; payment_received_at: string | null; cancelled_at: string | null }[]) {
      const stage = feeStageFromRow(f.status, f.payment_received_at, f.cancelled_at);
      if (stage === "cancelled") continue;
      const list = by.get(f.link_id) ?? [];
      list.push({ id: f.id, label: f.label ?? "Placement", amount: Number(f.amount_lakhs ?? 0), stage, billedOn: (f.proforma_sent_at ?? f.final_invoiced_at)?.slice(0, 10) ?? null, paidOn: f.payment_received_at?.slice(0, 10) ?? null });
      by.set(f.link_id, list);
    }
    for (const r of rows) r.fees = by.get(r.linkId) ?? [];
  }

  return (
    <div className="max-w-[1500px] mx-auto px-5 py-8">
      <h1 className="ros-page-title mb-1">Placements</h1>
      <p className="text-[14px] text-slate-500 dark:text-slate-400 mb-6">
        Every placed candidate, their joining date, confirmation of what actually happened, and their 30/90/180-day
        retention check-ins -- the source of truth this updates everywhere else (Candidates, mandate pipelines,
        Billing).
      </p>
      {isAdmin && (
        <div className="mb-5 flex gap-2" role="tablist" aria-label="Placements view">
          {[{ key: "tracker", label: "Tracker" }, { key: "analysis", label: "Fee analysis" }].map((t) => {
            const on = (t.key === "analysis") === analysis;
            return (
              <Link key={t.key} href={t.key === "analysis" ? "/placements?view=analysis" : "/placements"} role="tab" aria-selected={on} className={`rounded-full border px-4 py-1.5 text-[14px] font-medium ${on ? "border-teal-600 bg-teal-600 text-white" : "border-slate-200 bg-white text-slate-700 hover:border-teal-400 dark:border-slate-700 dark:bg-slate-900 dark:text-slate-200"}`}>{t.label}</Link>
            );
          })}
        </div>
      )}
      {analysis && admin ? (
        <FeeAnalysisView a={await loadFeeAnalysis(admin)} />
      ) : (
        <>
          <PlacementsView initialRows={rows} fetchError={error?.message ?? null} isAdmin={isAdmin} currentUserId={user.id} />
          <DroppedSection rows={await loadDropped(supabase, admin, isAdmin).catch(() => [])} isAdmin={isAdmin} />
        </>
      )}
    </div>
  );
}
